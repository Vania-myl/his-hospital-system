import request from './request'
export const prescriptions = params => request.get('/prescription/list', { params })
export const prescribe = data => request.post('/prescription', data)
export const cancelPrescription = id => request.put(`/prescription/${id}/cancel`)
export const dispense = id => request.put(`/prescription/${id}/dispense`)
export const returnDrug = (id, reason) => request.put(`/prescription/${id}/return`, { reason })
export const drugs = params => request.get('/pharmacy/drugs', { params })
export const saveDrug = data => data.id ? request.put(`/drug/${data.id}`, data) : request.post('/drug', data)
export const disableDrug = id => request.delete(`/drug/${id}`)
export const stock = (id, data) => request.post(`/drug/${id}/stock`, data)
export const transactions = params => request.get('/pharmacy/transactions', { params })
